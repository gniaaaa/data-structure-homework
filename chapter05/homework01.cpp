/*
第一题

给定两个均含有 n 个元素的整型数组 A 和 B，判定 B 是否是 A 循环右移若干位得到的。

思路：
设 A 循环右移 k 位得到 B（k = 0,1,...,n-1），则 B 的第 j 个元素来自
A 的第 (j-k+n)%n 个元素，等价地，对每个 i 都有

        B[(i + k) % n] == A[i]

于是只要枚举 k = 0..n-1，逐个验证这个条件即可。k = 0 对应"不移位"，
所以 A 与 B 完全相同时也能够正确判为真。

剪枝：i = 0 时条件变成 B[k] == A[0]，因此只需在 A[0] 出现过的位置上试 k。
A 中元素互不相同时，最多只有 1 个候选 k；A 中元素大量重复时（如全相等），
候选仍可达 n 个。

时间复杂度：最坏 O(n^2)（A 中元素大量重复），最好 O(n)；空间复杂度 O(1)。
若要求严格的 O(n)，可以改用在 A+A 上匹配 B 的 KMP 算法，
或对 A 求最小正周期后直接比较。
*/

#include<iostream>
using namespace std;

bool isRightMove(int A[],int B[],int n){
    if(n<=0){
        return true;                        //空数组视为自身的循环移位
    }
    for(int k=0;k<n;k++){
        if(B[k]!=A[0]){
            continue;                       //剪枝：i=0 时必须 B[k]==A[0]
        }
        int i=1;
        while(i<n && B[(i+k)%n]==A[i]){
            i++;
        }
        if(i==n){
            return true;                    //找到了满足条件的 k
        }
    }
    return false;
}

void Test(const char *name,int A[],int B[],int n){
    cout<<name<<" -> "<<(isRightMove(A,B,n)?"是循环右移":"不是循环右移")<<endl;
}

int main(){
    int a1[]={1,2,3,4,5};
    int b1[]={4,5,1,2,3};                   //A 右移 2 位
    int b2[]={3,4,5,1,2};                   //A 右移 3 位
    int b3[]={1,2,3,4,5};                   //A 右移 0 位
    int b4[]={1,2,3,5,4};                   //不是循环移位
    int b5[]={2,1,3,4,5};                   //只是交换了两个元素，不是

    Test("A=1 2 3 4 5  B=4 5 1 2 3",a1,b1,5);
    Test("A=1 2 3 4 5  B=3 4 5 1 2",a1,b2,5);
    Test("A=1 2 3 4 5  B=1 2 3 4 5",a1,b3,5);
    Test("A=1 2 3 4 5  B=1 2 3 5 4",a1,b4,5);
    Test("A=1 2 3 4 5  B=2 1 3 4 5",a1,b5,5);

    //元素有重复的情况：A 与 B 中 1、2 各出现两次，仍能正确判定
    int a2[]={1,2,1,2,3};
    int b6[]={1,2,3,1,2};                   //A 右移 3 位
    int b7[]={1,1,2,2,3};                   //不是
    Test("A=1 2 1 2 3  B=1 2 3 1 2",a2,b6,5);
    Test("A=1 2 1 2 3  B=1 1 2 2 3",a2,b7,5);

    //全部元素相同
    int a3[]={7,7,7};
    int b8[]={7,7,7};
    Test("A=7 7 7      B=7 7 7   ",a3,b8,3);

    return 0;
}
